/** Odpověď Vision pro jednu stránku (i s rozměry obrázku, které tabulka potřebuje). */
export function visionStranka(slova: SlovoVision[], sirka: number, vyska: number) {
  return {
    responses: [{
      fullTextAnnotation: {
        pages: [{
          width: sirka,
          height: vyska,
          blocks: [{
            paragraphs: [{
              words: slova.map(([t, ...v]) => ({
                symbols: [{ text: t }],
                boundingBox: { vertices: [0, 1, 2, 3].map((i) => ({ x: v[i * 2], y: v[i * 2 + 1] })) },
              })),
            }],
          }],
        }],
      },
    }],
  };
}

